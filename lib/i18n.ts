// ─── Runtime ──────────────────────────────────────────────────────────────────

const STORAGE_KEY = '@seeker_lang';
let currentLang: Lang = 'en';
const listeners = new Set<(lang: Lang) => void>();

export function getLang(): Lang {
  return currentLang;
}

export async function loadSavedLang(): Promise<Lang> {
  try {
    const v = await AsyncStorage.getItem(STORAGE_KEY);
    if (v && (LANGUAGES.some(l => l.code === v))) {
      currentLang = v as Lang;
    }
  } catch (_) {}
  return currentLang;
}

export async function setLang(lang: Lang) {
  currentLang = lang;
  try { await AsyncStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
  listeners.forEach(fn => fn(lang));
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = T[currentLang] || T.en;
  let v = dict[key] ?? T.en[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      v = v.replace(`{${k}}`, String(vars[k]));
    }
  }
  return v;
}

// React hook so components re-render on language change
export function useLang(): Lang {
  const [lang, setLangState] = useState<Lang>(currentLang);
  useEffect(() => {
    const handler = (l: Lang) => setLangState(l);
    listeners.add(handler);
    return () => { listeners.delete(handler); };
  }, []);
  return lang;
}
